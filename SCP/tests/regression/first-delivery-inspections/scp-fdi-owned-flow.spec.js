const fs = require('fs');
const { randomUUID } = require('crypto');
const { test, expect } = require('../../../fixtures/baseTest');
const { FirstDeliveryInspectionsPage } = require('../../../pages/first-delivery-inspections/first-delivery-inspections.page');
const { readInventoryApi } = require('../../../utils/inventory-data');
const { complete, missing } = require('../../../utils/inventory-recovery');
const { managedStep } = require('../../../utils/scp-step');
const { ScpBlocked } = require('../../../utils/scp-readonly');
const { isHeadless } = require('../../../utils/execution-mode');

test('SCP-FDI-101 Owned delivery: self-assignment, saved draft, photo and completed inspection', async ({ scpProject: ctx, executionJournal: journal }, info) => {
  info.setTimeout(600000);
  if (process.env.SCP_FDI_OWNED_MUTATIONS !== 'true') throw new ScpBlocked('Enable SCP_FDI_OWNED_MUTATIONS for the dedicated owned-delivery flow');
  if (!new URL(ctx.config.baseUrl).hostname.startsWith('stg-')) throw new ScpBlocked('Owned inspection mutations are limited to configured staging');
  const file = process.env.SCP_FDI_OWNED_DATA;
  if (!file || !fs.existsSync(file)) throw new ScpBlocked('SCP_FDI_OWNED_DATA must identify a passed, dedicated delivery allocation');
  const target = JSON.parse(fs.readFileSync(file, 'utf8'));
  expect(target.project).toBe(ctx.config.projectName);
  expect(target.sourceCase).toBeTruthy(); expect(target.data?.grn?.file_size).toBeGreaterThan(0);
  expect(target.data.submittalNumber).not.toBe('SUB-2026-525');
  journal.scenario.module = 'First Delivery Inspection';
  journal.scenario.objective = 'Complete only the inspection generated by a validated owned delivery, preserving project configuration';
  const view = new FirstDeliveryInspectionsPage(ctx.page, ctx.config);
  const runId = journal.data('ownedFdiRunId', () => randomUUID().slice(0, 12));
  const body = await readInventoryApi(ctx.page, 'first_delivery_inspection/list_inspections/', { material: target.master.material_master_id });
  expect(Array.isArray(body.data), 'FDI list must return authoritative inspection records').toBe(true);
  const records = body.data.filter(record => JSON.stringify(record).includes(target.data.submittalNumber) && JSON.stringify(record).includes(target.master.material_name));
  expect(records, 'The passed delivery must identify one unique inspection').toHaveLength(1);
  const inspection = records[0]; expect(inspection.inspection_id).toBeTruthy();
  if (journal.state.data.ownedInspection) expect(journal.state.data.ownedInspection.inspection_id).toBe(inspection.inspection_id);
  journal.setData('ownedInspection', inspection);
  const forbidden = [];
  const origin = new URL(ctx.config.baseUrl).origin;
  const guard = route => {
    const request = route.request(); const url = new URL(request.url());
    if (url.origin !== origin || ['GET', 'HEAD', 'OPTIONS'].includes(request.method())) return route.continue();
    const ownedPath = url.pathname.startsWith(`/api/first_delivery_inspection/${inspection.inspection_id}/`) &&
      /\/(self_assign|upload_photo)\/$/.test(url.pathname);
    const ownedResponse = /^\/api\/first_delivery_inspection\/(save_responses|update_responses|submit_responses)\/$/.test(url.pathname) &&
      String(request.postData() || '').includes(inspection.inspection_id);
    if (ownedPath || ownedResponse) return route.continue();
    forbidden.push({ method: request.method(), path: url.pathname }); return route.abort('blockedbyclient');
  };
  await ctx.scpSession.context.route('**/api/**', guard);
  async function row() {
    await ctx.page.goto(new URL('/first-delivery-inspections', ctx.config.baseUrl).href, { waitUntil: 'domcontentloaded' });
    await ctx.projectSelector.expectActiveProject(target.project);
    await ctx.siteSelector.ensureSite(target.site);
    const filters = ctx.page.locator('main').getByRole('combobox');
    await expect(filters).toHaveCount(3);
    await filters.nth(0).selectOption({ label: target.master.material_name });
    await filters.nth(1).selectOption({ label: target.data.supplier });
    const selected = view.rows().filter({ has: ctx.page.getByRole('cell', { name: target.data.submittalNumber, exact: true }) });
    await expect(selected).toHaveCount(1); return selected;
  }
  const email = ctx.config.username;
  async function report() {
    const selected = await row(); const record = await view.rowData(selected);
    if (/Inspection completed/i.test(record.status)) return { done: true, record };
    if (!record.assignedTo.toLowerCase().includes(email.toLowerCase())) throw new ScpBlocked('The owned inspection is not assigned to the current account');
    await view.openReport(selected); return { done: false, record };
  }
  const ids = ['fdi-self-assign', 'fdi-draft', 'fdi-photo', 'fdi-complete'];
  journal.define(ids.map((id, index) => ({ id, name: id, dependsOn: index ? [ids[index - 1]] : [] })));
  const step = (index, name, action, verify) => managedStep(test, ctx.page, name, action,
    { id: ids[index], dependsOn: index ? [ids[index - 1]] : [], mutation: true, verify });
  try {
    await step(0, 'Assign only the owned inspection to the current account', async () => {
      const selected = await row();
      if (!await selected.getByRole('button', { name: /Self assign/i }).isVisible()) {
        info.annotations.push({ type: 'not-accessible', description: 'Self assignment is not available to this account on the owned inspection' });
        throw new ScpBlocked('Self assignment is not available to the current account on the owned inspection');
      }
      await view.selfAssign(selected, email);
    }, async () => {
      const record = await view.rowData(await row());
      if (/Inspection completed/i.test(record.status) || record.assignedTo.toLowerCase().includes(email.toLowerCase())) return complete(record);
      if (!/Auditor not yet assigned/i.test(record.status)) throw new ScpBlocked('The owned inspection is assigned to another account');
      return missing();
    });
    await step(1, 'Save and reopen the owned inspection draft with exact answers', async () => {
      await report(); await view.fillReport(runId); await view.saveProgress();
    }, async () => {
      const current = await report(); if (current.done) return complete(current.record);
      const inputs = await view.reportQuestions();
      const values = await inputs.evaluateAll(elements => elements.map(element => element.value));
      return values.every((value, index) => value === `Automated inspection ${runId} answer ${index + 1}`) ? complete({ answers: values }) : missing();
    });
    await step(2, 'Upload one QA evidence image to the owned inspection', async () => {
      await report(); const photo = info.outputPath('owned-inspection-evidence.png');
      await ctx.page.screenshot({ path: photo }); await view.uploadPhoto(photo);
      await info.attach('owned-inspection-evidence', { path: photo, contentType: 'image/png' });
    }, async () => {
      const current = await report(); if (current.done) return complete(current.record);
      const configuration = (await readInventoryApi(ctx.page, 'fdi_config/')).data;
      expect(typeof configuration.enable_photo_upload).toBe('boolean');
      if (!configuration.enable_photo_upload) {
        expect(configuration.photos_mandatory, 'Disabled photo uploads cannot require a photo').toBe(false);
        return complete({ notApplicable: 'Photo uploads are disabled in the project configuration' });
      }
      await expect(ctx.page.getByRole('button', { name: 'Add photo', exact: true })).toBeVisible({ timeout: 15000 });
      const photos = await readInventoryApi(ctx.page, `first_delivery_inspection/${inspection.inspection_id}/photos/`);
      expect(Array.isArray(photos.data), 'Saved photos must be verified before another image is uploaded').toBe(true);
      return photos.data.length ? complete({ photoCount: photos.data.length }) : missing();
    });
    await step(3, 'Submit the owned inspection and confirm persisted completion', async () => {
      await report(); await view.submit();
    }, async () => {
      const record = await view.rowData(await row());
      return /Inspection completed/i.test(record.status) ? complete({ inspection_id: inspection.inspection_id, ...record }) : missing();
    });
    journal.setData('completedOwnedInspection', { inspection_id: inspection.inspection_id, ...await view.rowData(await row()) });
    await info.attach('owned-inspection-completed', { body: await ctx.page.screenshot({ fullPage: isHeadless() }), contentType: 'image/png' });
  } finally {
    await ctx.scpSession.context.unroute('**/api/**', guard);
    journal.setData('forbiddenFdiWrites', forbidden);
    expect(forbidden, 'Only the owned inspection may be changed; shared configuration and provider sync are prohibited').toEqual([]);
  }
});
